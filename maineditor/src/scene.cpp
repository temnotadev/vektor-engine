static std::ostream& writeScriptPath(std::ostream& stream, const std::string& path) {
    if (path.find_first_of(" \t\"") == std::string::npos) return stream << path;
    return stream << std::quoted(path);
}

static void writePhysics(std::ostream& stream, const SceneObject& object) {
    if (!object.physicsEnabled) {
        if (object.collisionOnly) stream << " body off";
        return;
    }

    stream << " body " << (object.physicsDynamic ? "dynamic" : "static");
    if (object.physicsDynamic) stream << " mass " << object.mass;
    if (object.friction != 0.2f) stream << " friction " << object.friction;
    if (object.restitution != 0.0f) stream << " restitution " << object.restitution;
}

static void readLightOptions(std::istringstream& stream, Light& light) {
    std::vector<std::string> options;
    std::string option;
    while (stream >> option) options.push_back(option);

    for (size_t i = 0; i < options.size(); ++i) {
        if (options[i] == "strict") {
            light.strictAttenuation = true;
            if (i + 1 < options.size() && (options[i + 1] == "on" || options[i + 1] == "off")) {
                light.strictAttenuation = options[i + 1] == "on";
                ++i;
            }
        } else if (options[i] == "intensity" && i + 1 < options.size()) {
            light.intensity = std::strtof(options[++i].c_str(), nullptr);
        }
    }
}

std::string Scene::makeUniqueName(const std::string& prefix) const {
    int n = 1;
    while (true) {
        std::string c = prefix + std::to_string(n);
        bool found = false;
        for (auto& o : objects) if (o.name == c) { found = true; break; }
        if (!found) for (auto& l : lights) if (l.name == c) { found = true; break; }
        if (!found) for (auto& s : sounds) if (s.name == c) { found = true; break; }
        if (!found) return c;
        ++n;
    }
}

std::string Scene::makeUniqueMaterialName(const std::string& prefix) const {
    int n = 1;
    while (true) {
        std::string c = prefix + std::to_string(n);
        if (!materials.count(c)) return c;
        ++n;
    }
}

int Scene::addObject(ObjType type, Vec3 pos, Vec3 size, Vec3 color, const std::string& modelId) {
    SceneObject o;
    o.name    = makeUniqueName(modelId.empty() ? objTypeName(type) : modelId);
    o.type    = type;
    o.pos     = pos;
    o.size    = size;
    o.color   = color;
    o.modelId = modelId;
    objects.push_back(o);
    return (int)objects.size() - 1;
}

int Scene::addPointLight(Vec3 pos, Vec3 color, float range) {
    Light l;
    l.name = makeUniqueName("lamp");
    l.type = LightType::Point;
    l.pos = pos; l.color = color; l.range = range;
    lights.push_back(l);
    return (int)lights.size() - 1;
}

int Scene::addSpotLight(Vec3 pos, Vec3 dir, Vec3 color, float range, float outerDeg, float innerDeg) {
    Light l;
    l.name = makeUniqueName("spot");
    l.type = LightType::Spot;
    l.pos = pos; l.dir = dir; l.color = color;
    l.range = range; l.outerDeg = outerDeg; l.innerDeg = innerDeg;
    lights.push_back(l);
    return (int)lights.size() - 1;
}

int Scene::addSound(Vec3 pos, const std::string& path) {
    SoundObject s;
    s.name = makeUniqueName("sound");
    s.pos = pos;
    s.path = path;
    sounds.push_back(s);
    return (int)sounds.size() - 1;
}

void Scene::removeObject(int idx) {
    if (idx >= 0 && idx < (int)objects.size()) objects.erase(objects.begin() + idx);
}
void Scene::removeLight(int idx) {
    if (idx >= 0 && idx < (int)lights.size()) lights.erase(lights.begin() + idx);
}
void Scene::removeSound(int idx) {
    if (idx < 0 || idx >= (int)sounds.size()) return;
    if (audio) {
        audio->stop(sounds[idx].name);
        audio->unload(sounds[idx].name);
    }
    sounds.erase(sounds.begin() + idx);
}

std::string Scene::generateScript() const {
    std::ostringstream ss;
    ss << std::fixed << std::setprecision(3);
    ss << "# Auto-generated by Scribe Editor\n";
    ss << "# Edit below and press Apply, or use the viewport tools.\n\n";

    if (!textures.empty()) {
        for (auto& [id, p] : textures) {
            ss << "texture " << id << " ";
            writeScriptPath(ss, p) << "\n";
        }
        ss << "\n";
    }
    if (!models.empty()) {
        for (auto& [id, e] : models) {
            ss << "model " << id << " ";
            writeScriptPath(ss, e.path);
            if (e.raw) ss << " raw";
            ss << "\n";
        }
        ss << "\n";
    }
    if (!materials.empty()) {
        for (auto& [id, m] : materials) {
            ss << "material " << id
               << " color " << m.color.x << " " << m.color.y << " " << m.color.z;
            if (!m.texId.empty())       ss << " texture " << m.texId;
            if (!m.normalTexId.empty()) ss << " normal " << m.normalTexId;
            if (m.metallic != 0.0f)     ss << " metallic " << m.metallic;
            if (m.smoothness != 0.5f)   ss << " smoothness " << m.smoothness;
            if (m.reflectivity != 0.0f) ss << " reflectivity " << m.reflectivity;
            if (m.ssr)                  ss << " ssr on";
            ss << "\n";
        }
        ss << "\n";
    }
    if (!sounds.empty()) {
        for (auto& s : sounds) {
            if (s.path.empty()) continue;
            ss << "sound " << s.name << " ";
            writeScriptPath(ss, s.path);
            ss << " pos " << s.pos.x << " " << s.pos.y << " " << s.pos.z;
            if (s.volume != 1.0f) ss << " volume " << s.volume;
            if (s.pan != 0.0f)    ss << " pan " << s.pan;
            if (s.range != 10.0f) ss << " range " << s.range;
            if (s.loop)           ss << " loop";
            if (s.autoplay)       ss << " autoplay";
            if (s.spatial)        ss << " spatial";
            ss << "\n";
        }
        ss << "\n";
    }
    if (playerController) {
        ss << "builtin player";
        if (!playerGravity) ss << " gravity off";
        ss << "\n\n";
    }

    for (auto& o : objects) {
        if (o.collisionOnly) {
            ss << "collider " << o.name
               << " pos "  << o.pos.x << " " << o.pos.y << " " << o.pos.z
               << " size " << o.size.x << " " << o.size.y << " " << o.size.z;
            if (o.rot.x != 0.0f || o.rot.y != 0.0f || o.rot.z != 0.0f)
                ss << " rot " << o.rot.x << " " << o.rot.y << " " << o.rot.z;
            writePhysics(ss, o);
            ss << "\n";
            continue;
        }
        const std::string typeStr = o.modelId.empty() ? objTypeName(o.type) : o.modelId;
        ss << "spawn " << o.name << " " << typeStr
           << " pos "   << o.pos.x   << " " << o.pos.y   << " " << o.pos.z
           << " size "  << o.size.x  << " " << o.size.y  << " " << o.size.z;
        if (o.rot.x != 0.0f || o.rot.y != 0.0f || o.rot.z != 0.0f)
            ss << " rot " << o.rot.x << " " << o.rot.y << " " << o.rot.z;
        ss << " color " << o.color.x << " " << o.color.y << " " << o.color.z;
        if (!o.materialId.empty()) ss << " material " << o.materialId;
        if (o.uvScale != 1.0f)     ss << " uvscale " << o.uvScale;
        if (o.textureWrap == TextureWrapMode::Clamp) ss << " wrap clamp";
        if (o.textureFilter == TextureFilterMode::Nearest) ss << " filter nearest";
        writePhysics(ss, o);
        for (size_t i = 0; i < o.materialTexIds.size(); ++i)
            if (!o.materialTexIds[i].empty()) ss << " mattex " << i << " " << o.materialTexIds[i];
        ss << "\n";
    }
    if (!lights.empty()) ss << "\n";

    for (auto& l : lights) {
        ss << "light ";
        switch (l.type) {
            case LightType::Point:
                ss << "point " << l.name
                   << " " << l.pos.x   << " " << l.pos.y   << " " << l.pos.z
                   << " " << l.color.x << " " << l.color.y << " " << l.color.z
                   << " " << l.range;
                if (l.strictAttenuation) ss << " strict";
                if (l.intensity != 1.0f) ss << " intensity " << l.intensity;
                ss << "\n";
                break;
            case LightType::Spot:
{
    ss << "spot " << l.name
       << " " << l.pos.x << " " << l.pos.y << " " << l.pos.z
       << " " << l.dir.x << " " << l.dir.y << " " << l.dir.z
       << " " << l.color.x << " " << l.color.y << " " << l.color.z
       << " " << l.range
       << " " << l.outerDeg
       << " " << l.innerDeg;

    ss << " intensity " << l.intensity;
    ss << "\n";
    break;
}
            case LightType::Sun:
                ss << "sun " << l.name
                   << " " << l.dir.x   << " " << l.dir.y   << " " << l.dir.z
                   << " " << l.color.x << " " << l.color.y << " " << l.color.z;
                if (l.intensity != 1.0f) ss << " intensity " << l.intensity;
                ss << "\n";
                break;
        }
    }
    for (const auto& global : scriptGlobals) ss << global << "\n";
    if (!scriptGlobals.empty()) ss << "\n";
    for (const auto& event : scriptEvents) {
        ss << "\non " << event.type;
        if (event.type == "key") ss << " " << event.key;
        ss << "\n";
        for (const auto& command : event.commands) ss << "  " << command << "\n";
        ss << "end\n";
    }
    return ss.str();
}

void Scene::loadScript(const std::string& text) {
    objects.clear(); lights.clear(); sounds.clear(); scriptEvents.clear(); scriptGlobals.clear(); scriptVariables.clear();
    textures.clear(); materials.clear(); models.clear();
    playerController = false;
    playerGravity = true;
    if (audio) {
        audio->stopAll();
        audio->unloadAll();
    }

    std::istringstream stream(text);
    std::string raw;
    ScriptEvent* activeEvent = nullptr;
    bool insideEvent = false;
    while (std::getline(stream, raw)) {
        // Strip `#` / `//` comments only at start-of-line or after whitespace
        size_t cpos = std::string::npos;
        for (size_t i = 0; i < raw.size(); ++i) {
            if (i == 0 || raw[i-1] == ' ' || raw[i-1] == '\t') {
                if (raw[i] == '#') { cpos = i; break; }
                if (i+1 < raw.size() && raw[i] == '/' && raw[i+1] == '/') { cpos = i; break; }
            }
        }

        if (cpos != std::string::npos) raw = raw.substr(0, cpos);

        std::istringstream ls(raw);
        std::string cmd;
        if (!(ls >> cmd)) continue;

        if (cmd == "on") {
            std::string eventType, key;
            ls >> eventType;
            insideEvent = !eventType.empty();
            activeEvent = nullptr;
            if (eventType == "key" && ls >> key) {
                scriptEvents.push_back({eventType, key, {}});
                activeEvent = &scriptEvents.back();
            } else if (eventType == "frame") {
                scriptEvents.push_back({eventType, {}, {}});
                activeEvent = &scriptEvents.back();
            }
            continue;
        } else if (cmd == "end") {
            activeEvent = nullptr;
            insideEvent = false;
            continue;
        } else if (insideEvent) {
            const size_t first = raw.find_first_not_of(" \t");
            if (first != std::string::npos && activeEvent)
                activeEvent->commands.push_back(raw.substr(first));
            continue;
        } else if (cmd == "var") {
            std::string name, value;
            if (ls >> name >> value && !name.empty() && name[0] == '$') {
                scriptGlobals.push_back(raw);
                scriptVariables[name] = std::strtof(value.c_str(), nullptr);
            }
        } else if (cmd == "texture") {
            std::string id, path;
            if (ls >> id >> std::quoted(path)) textures[id] = path;
        } else if (cmd == "material") {
            std::string id;
            if (!(ls >> id)) continue;
            Material material;
            material.name = id;
            std::string key;
            while (ls >> key) {
                if (key == "color") {
                    ls >> material.color.x >> material.color.y >> material.color.z;
                } else if (key == "texture" || key == "normal") {
                    std::string textureId;
                    if (!(ls >> textureId)) break;
                    std::string& slot = (key == "texture") ? material.texId : material.normalTexId;
                    slot = (textureId == "none") ? "" : textureId;
                } else if (key == "metallic") {
                    ls >> material.metallic;
                } else if (key == "smoothness") {
                    ls >> material.smoothness;
                } else if (key == "reflectivity") {
                    ls >> material.reflectivity;
                } else if (key == "ssr") {
                    std::string value;
                    if (!(ls >> value)) break;
                    material.ssr = value == "on" || value == "true" || value == "1";
                } else {
                    break;
                }
            }
            materials[id] = material;
        } else if (cmd == "model") {
            std::string id, path, opt;
            if (!(ls >> id >> std::quoted(path))) continue;
            ModelEntry e; e.path = path;
            if (ls >> opt && opt == "raw") e.raw = true;
            models[id] = e;
        } else if (cmd == "sound") {
            SoundObject s;
            if (!(ls >> s.name >> std::quoted(s.path))) continue;
            std::vector<std::string> opts;
            std::string opt;
            while (ls >> opt) opts.push_back(opt);
            for (size_t i = 0; i < opts.size();) {
                if (opts[i] == "pos" && i + 3 < opts.size()) {
                    s.pos.x = std::strtof(opts[i + 1].c_str(), nullptr);
                    s.pos.y = std::strtof(opts[i + 2].c_str(), nullptr);
                    s.pos.z = std::strtof(opts[i + 3].c_str(), nullptr);
                    i += 4;
                } else if (opts[i] == "volume" && i + 1 < opts.size()) {
                    s.volume = std::clamp(std::strtof(opts[i + 1].c_str(), nullptr), 0.0f, 1.0f);
                    i += 2;
                } else if (opts[i] == "pan" && i + 1 < opts.size()) {
                    s.pan = std::clamp(std::strtof(opts[i + 1].c_str(), nullptr), -1.0f, 1.0f);
                    i += 2;
                } else if (opts[i] == "range" && i + 1 < opts.size()) {
                    s.range = std::max(0.01f, std::strtof(opts[i + 1].c_str(), nullptr));
                    i += 2;
                } else if (opts[i] == "loop") {
                    if (i + 1 < opts.size() && (opts[i + 1] == "on" || opts[i + 1] == "off")) {
                        s.loop = opts[i + 1] == "on";
                        i += 2;
                    } else {
                        s.loop = true;
                        ++i;
                    }
                } else if (opts[i] == "autoplay") {
                    if (i + 1 < opts.size() && (opts[i + 1] == "on" || opts[i + 1] == "off")) {
                        s.autoplay = opts[i + 1] == "on";
                        i += 2;
                    } else {
                        s.autoplay = true;
                        ++i;
                    }
                } else if (opts[i] == "spatial") {
                    if (i + 1 < opts.size() && (opts[i + 1] == "on" || opts[i + 1] == "off")) {
                        s.spatial = opts[i + 1] == "on";
                        i += 2;
                    } else {
                        s.spatial = true;
                        ++i;
                    }
                } else {
                    ++i;
                }
            }
            sounds.push_back(s);
        } else if (cmd == "collider") {
            SceneObject o;
            o.collisionOnly = true;
            o.physicsEnabled = true;
            if (!(ls >> o.name)) continue;
            std::string key;
            while (ls >> key) {
                if      (key == "pos")  ls >> o.pos.x >> o.pos.y >> o.pos.z;
                else if (key == "size") ls >> o.size.x >> o.size.y >> o.size.z;
                else if (key == "rot")  ls >> o.rot.x >> o.rot.y >> o.rot.z;
                else if (key == "body") {
                    std::string mode;
                    if (!(ls >> mode)) break;
                    if (mode == "off") o.physicsEnabled = false;
                    else if (mode == "static") { o.physicsEnabled = true; o.physicsDynamic = false; }
                    else if (mode == "dynamic") { o.physicsEnabled = true; o.physicsDynamic = true; }
                }
                else if (key == "mass") ls >> o.mass;
                else if (key == "friction") ls >> o.friction;
                else if (key == "restitution") ls >> o.restitution;
                else break;
            }
            objects.push_back(o);
        } else if (cmd == "builtin") {
            std::string name;
            if (ls >> name && name == "player") {
                playerController = true;
                std::string option;
                while (ls >> option) {
                    if (option == "gravity") {
                        std::string setting;
                        if (ls >> setting) playerGravity = setting != "off";
                    }
                }
            }
        } else if (cmd == "spawn") {
            SceneObject o;
            std::string typeTok;
            if (!(ls >> o.name >> typeTok)) continue;

            if (typeTok == "cube" || typeTok == "sphere" || typeTok == "quad") {
                o.type = objTypeFromName(typeTok);
            } else {
                o.type = ObjType::Cube;   // default; unused when modelId set
                o.modelId = typeTok;
            }

            std::string key;
            while (ls >> key) {
                if      (key == "pos")   ls >> o.pos.x   >> o.pos.y   >> o.pos.z;
                else if (key == "size")  ls >> o.size.x  >> o.size.y  >> o.size.z;
                else if (key == "scale") { float s; ls >> s; o.size = {s,s,s}; }
                else if (key == "rot")   ls >> o.rot.x   >> o.rot.y   >> o.rot.z;
                else if (key == "body") {
                    std::string mode;
                    if (!(ls >> mode)) break;
                    if (mode == "off") o.physicsEnabled = false;
                    else if (mode == "static") { o.physicsEnabled = true; o.physicsDynamic = false; }
                    else if (mode == "dynamic") { o.physicsEnabled = true; o.physicsDynamic = true; }
                }
                else if (key == "mass") ls >> o.mass;
                else if (key == "friction") ls >> o.friction;
                else if (key == "restitution") ls >> o.restitution;
                else if (key == "color") ls >> o.color.x >> o.color.y >> o.color.z;
                else if (key == "material") {
                    std::string materialId;
                    if (ls >> materialId) o.materialId = (materialId == "none") ? "" : materialId;
                }
                // Legacy form: "tex <id>" - promote the texture to a material so old
                // scenes keep their look when re-saved with the material system.
                else if (key == "tex") {
                    std::string textureId;
                    if (ls >> textureId) {
                        if (!textureId.empty()) {
                            if (!materials.count(textureId)) {
                                Material material;
                                material.name = textureId;
                                material.texId = textureId;
                                materials[textureId] = material;
                            }
                            o.materialId = textureId;
                        }
                    }
                }
                else if (key == "uvscale") ls >> o.uvScale;
                else if (key == "wrap") {
                    std::string value;
                    if (ls >> value) {
                        if (value == "clamp") o.textureWrap = TextureWrapMode::Clamp;
                        else if (value == "repeat") o.textureWrap = TextureWrapMode::Repeat;
                        else std::fprintf(stderr, "[scene] unknown texture wrap mode: %s\n", value.c_str());
                    }
                }
                else if (key == "filter") {
                    std::string value;
                    if (ls >> value) {
                        if (value == "nearest") o.textureFilter = TextureFilterMode::Nearest;
                        else if (value == "linear") o.textureFilter = TextureFilterMode::Linear;
                        else std::fprintf(stderr, "[scene] unknown texture filter mode: %s\n", value.c_str());
                    }
                }
                else if (key == "mattex") {
                    int materialIndex = -1;
                    std::string textureId;
                    if (ls >> materialIndex >> textureId && materialIndex >= 0) {
                        if (o.materialTexIds.size() <= static_cast<size_t>(materialIndex))
                            o.materialTexIds.resize(static_cast<size_t>(materialIndex) + 1);
                        o.materialTexIds[materialIndex] = textureId;
                    }
                }
                else if (key == "emit") { float a,b,c; ls >> a >> b >> c; }
                else if (key == "collide") { std::string v; ls >> v; }
                else break;
            }
            objects.push_back(o);
        } else if (cmd == "light") {
            std::string typeTok, nm;
            if (!(ls >> typeTok >> nm)) continue;
            Light l; l.name = nm;
            if (typeTok == "point") {
                l.type = LightType::Point;
                ls >> l.pos.x >> l.pos.y >> l.pos.z
                   >> l.color.x >> l.color.y >> l.color.z >> l.range;
                readLightOptions(ls, l);
                lights.push_back(l);
            } else if (typeTok == "spot") {
                l.type = LightType::Spot;
                ls >> l.pos.x >> l.pos.y >> l.pos.z
                   >> l.dir.x >> l.dir.y >> l.dir.z
                   >> l.color.x >> l.color.y >> l.color.z
                   >> l.range >> l.outerDeg >> l.innerDeg;
                readLightOptions(ls, l);
                lights.push_back(l);
            } else if (typeTok == "sun") {
                l.type = LightType::Sun;
                ls >> l.dir.x >> l.dir.y >> l.dir.z
                   >> l.color.x >> l.color.y >> l.color.z;
                readLightOptions(ls, l);
                lights.push_back(l);
            }
        } else if (cmd == "set") {
            std::string target, property, setting;
            if (!(ls >> target >> property >> setting)) continue;
            if (property == "strict" && (setting == "on" || setting == "off")) {
                for (auto& light : lights) {
                    if (light.name == target && light.type == LightType::Point)
                        light.strictAttenuation = setting == "on";
                }
            } else if (property == "intensity") {
                for (auto& light : lights) {
                    if (light.name == target)
                        light.intensity = std::max(0.0f, std::strtof(setting.c_str(), nullptr));
                }
            } else if (target == "material") {
                // set material <id> <property> <value>
                Material& material = materials[property];
                material.name = property;
                if (setting == "texture" || setting == "normal") {
                    std::string textureId;
                    if (!(ls >> textureId)) continue;
                    std::string& slot = (setting == "texture") ? material.texId : material.normalTexId;
                    slot = (textureId == "none") ? "" : textureId;
                } else if (setting == "color") {
                    ls >> material.color.x >> material.color.y >> material.color.z;
                } else if (setting == "metallic") {
                    ls >> material.metallic;
                } else if (setting == "smoothness") {
                    ls >> material.smoothness;
                } else if (setting == "reflectivity") {
                    ls >> material.reflectivity;
                } else if (setting == "ssr") {
                    std::string value;
                    if (ls >> value) material.ssr = value == "on" || value == "true" || value == "1";
                }
            } else if (property == "material") {
                for (auto& object : objects) {
                    if (object.name == target)
                        object.materialId = setting == "none" ? "" : setting;
                }
            }
        }
    }
    if (audio) {
        for (auto& s : sounds) {
            if (s.path.empty()) continue;
            if (audio->load(s.name, s.path) && s.autoplay)
                audio->play(s.name, s.loop, s.volume, s.pan);
        }
    }
}

namespace {
bool scriptNumber(const std::string& token,
                  const std::unordered_map<std::string, float>& variables,
                  float& value) {
    if (!token.empty() && token[0] == '$') {
        const auto it = variables.find(token);
        if (it == variables.end()) return false;
        value = it->second;
        return true;
    }

    char* end = nullptr;
    value = std::strtof(token.c_str(), &end);
    return end != token.c_str() && *end == '\0';
}

void setPosition(Scene& scene, const std::string& target, const Vec3& value, bool relative) {
    for (auto& object : scene.objects) {
        if (object.name == target) {
            if (relative) object.pos += value;
            else object.pos = value;
            return;
        }
    }
    for (auto& light : scene.lights) {
        if (light.name == target) {
            if (relative) light.pos += value;
            else light.pos = value;
            return;
        }
    }
    for (auto& sound : scene.sounds) {
        if (sound.name == target) {
            if (relative) sound.pos += value;
            else sound.pos = value;
            return;
        }
    }
}

void runScriptCommands(Scene& scene, const ScriptEvent& event) {
    int skippedIfDepth = 0;
    for (const std::string& command : event.commands) {
        std::istringstream input(command);
        std::string operation;
        if (!(input >> operation)) continue;

        if (operation == "if") {
            if (skippedIfDepth > 0) {
                ++skippedIfDepth;
                continue;
            }
            std::string leftToken, comparison, rightToken;
            float left = 0.0f, right = 0.0f;
            if (!(input >> leftToken >> comparison >> rightToken) ||
                !scriptNumber(leftToken, scene.scriptVariables, left) ||
                !scriptNumber(rightToken, scene.scriptVariables, right)) {
                std::fprintf(stderr, "[scene] invalid script if command: %s\n", command.c_str());
                skippedIfDepth = 1;
                continue;
            }
            const bool condition =
                comparison == "<"  ? left < right :
                comparison == ">"  ? left > right :
                comparison == "<=" ? left <= right :
                comparison == ">=" ? left >= right :
                comparison == "==" ? left == right :
                comparison == "!=" ? left != right : false;
            if (!condition) skippedIfDepth = 1;
            continue;
        }
        if (operation == "endif") {
            if (skippedIfDepth > 0) --skippedIfDepth;
            continue;
        }
        if (skippedIfDepth > 0) continue;

        if (operation == "var") {
            std::string name, valueToken;
            float value = 0.0f;
            if (input >> name >> valueToken && !name.empty() && name[0] == '$' &&
                scriptNumber(valueToken, scene.scriptVariables, value))
                scene.scriptVariables[name] = value;
        } else if (operation == "calc") {
            std::string name, leftToken, arithmetic, rightToken;
            float left = 0.0f, right = 0.0f;
            if (!(input >> name >> leftToken >> arithmetic >> rightToken) ||
                !scriptNumber(leftToken, scene.scriptVariables, left) ||
                !scriptNumber(rightToken, scene.scriptVariables, right))
                continue;

            float result = 0.0f;
            if      (arithmetic == "+") result = left + right;
            else if (arithmetic == "-") result = left - right;
            else if (arithmetic == "*") result = left * right;
            else if (arithmetic == "/") result = right != 0.0f ? left / right : 0.0f;
            else if (arithmetic == "min") result = std::min(left, right);
            else if (arithmetic == "max") result = std::max(left, right);
            else continue;
            if (!name.empty() && name[0] == '$') scene.scriptVariables[name] = result;
        } else if (operation == "move") {
            std::string target, xToken, yToken, zToken;
            float x = 0.0f, y = 0.0f, z = 0.0f;
            if (input >> target >> xToken >> yToken >> zToken &&
                scriptNumber(xToken, scene.scriptVariables, x) &&
                scriptNumber(yToken, scene.scriptVariables, y) &&
                scriptNumber(zToken, scene.scriptVariables, z))
                setPosition(scene, target, Vec3(x, y, z), true);
        } else if (operation == "set") {
            std::string target, property, xToken, yToken, zToken;
            if (!(input >> target >> property)) continue;
            if (property == "strict") {
                if (!(input >> xToken) || (xToken != "on" && xToken != "off")) continue;
                for (auto& light : scene.lights)
                    if (light.name == target && light.type == LightType::Point)
                        light.strictAttenuation = xToken == "on";
                continue;
            }
            if (property == "intensity") {
                if (!(input >> xToken)) continue;
                float intensity = 0.0f;
                if (!scriptNumber(xToken, scene.scriptVariables, intensity)) continue;
                for (auto& light : scene.lights)
                    if (light.name == target)
                        light.intensity = std::max(0.0f, intensity);
                continue;
            }
            float x = 0.0f, y = 0.0f, z = 0.0f;
            if (property == "pos" && input >> xToken >> yToken >> zToken &&
                scriptNumber(xToken, scene.scriptVariables, x) &&
                scriptNumber(yToken, scene.scriptVariables, y) &&
                scriptNumber(zToken, scene.scriptVariables, z))
                setPosition(scene, target, Vec3(x, y, z), false);

            for (auto& sound : scene.sounds) {
                if (sound.name != target) continue;
                if (property == "volume") {
                    float value = 0.0f;
                    if (input >> xToken && scriptNumber(xToken, scene.scriptVariables, value)) {
                        sound.volume = std::clamp(value, 0.0f, 1.0f);
                        if (scene.audio) scene.audio->setVolume(sound.name, sound.volume);
                    }
                } else if (property == "pan") {
                    float value = 0.0f;
                    if (input >> xToken && scriptNumber(xToken, scene.scriptVariables, value)) {
                        sound.pan = std::clamp(value, -1.0f, 1.0f);
                        if (scene.audio) scene.audio->setPan(sound.name, sound.pan);
                    }
                } else if (property == "loop") {
                    if (input >> xToken) {
                        sound.loop = xToken == "on" || xToken == "true" || xToken == "1";
                        if (scene.audio) scene.audio->setLooping(sound.name, sound.loop);
                    }
                } else if (property == "autoplay") {
                    if (input >> xToken)
                        sound.autoplay = xToken == "on" || xToken == "true" || xToken == "1";
                } else if (property == "playing") {
                    if (!(input >> xToken) || !scene.audio) continue;
                    const bool on = xToken == "on" || xToken == "true" || xToken == "1";
                    if (on) {
                        if (!scene.audio->exists(sound.name) && !sound.path.empty())
                            scene.audio->load(sound.name, sound.path);
                        scene.audio->play(sound.name, sound.loop, sound.volume, sound.pan);
                    } else {
                        scene.audio->pause(sound.name);
                    }
                }
            }
        } else if (operation == "play" || operation == "pause" ||
                   operation == "resume" || operation == "stop") {
            std::string target;
            if (!(input >> target)) continue;
            for (auto& sound : scene.sounds) {
                if (sound.name != target) continue;
                if (operation == "play") {
                    bool loop = sound.loop;
                    float volume = sound.volume, pan = sound.pan;
                    std::string option;
                    while (input >> option) {
                        if (option == "loop") loop = true;
                        else if (option == "once") loop = false;
                        else if (option == "volume") {
                            std::string token;
                            float value = 0.0f;
                            if (input >> token && scriptNumber(token, scene.scriptVariables, value))
                                volume = std::clamp(value, 0.0f, 1.0f);
                        } else if (option == "pan") {
                            std::string token;
                            float value = 0.0f;
                            if (input >> token && scriptNumber(token, scene.scriptVariables, value))
                                pan = std::clamp(value, -1.0f, 1.0f);
                        }
                    }
                    sound.loop = loop; sound.volume = volume; sound.pan = pan;
                    if (scene.audio) {
                        if (!scene.audio->exists(sound.name) && !sound.path.empty())
                            scene.audio->load(sound.name, sound.path);
                        scene.audio->play(sound.name, loop, volume, pan);
                    }
                } else if (scene.audio) {
                    if (operation == "pause") scene.audio->pause(sound.name);
                    else if (operation == "resume") scene.audio->resume(sound.name);
                    else scene.audio->stop(sound.name);
                }
            }
        } else if (operation == "audio") {
            std::string sub;
            if (!(input >> sub) || !scene.audio) continue;
            if (sub == "master") {
                std::string token;
                float value = 0.0f;
                if (input >> token && scriptNumber(token, scene.scriptVariables, value))
                    scene.audio->setMasterVolume(std::clamp(value, 0.0f, 1.0f));
            } else if (sub == "stopall") scene.audio->stopAll();
            else if (sub == "pauseall") scene.audio->pauseAll();
            else if (sub == "resumeall") scene.audio->resumeAll();
        }
    }
}
}

void Scene::runKeyEvent(const std::string& key) {
    for (const auto& event : scriptEvents)
        if (event.type == "key" && event.key == key)
            runScriptCommands(*this, event);
}

void Scene::runFrameEvents(float dt) {
    scriptVariables["$dt"] = dt;
    for (const auto& event : scriptEvents)
        if (event.type == "frame")
            runScriptCommands(*this, event);
}